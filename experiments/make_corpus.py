def build():
    corpus = []
    rid = 0
    for domain, prompts in A_DOMAINS.items():
        assert len(prompts) == 30, (domain, len(prompts))
        assert len(set(prompts)) == 30, domain
        for p in prompts:
            corpus.append({
                "request_id": rid,
                "part": "A",
                "domain": domain,
                "turns": [p],
                "max_new_tokens": 80,
            })
            rid += 1
    for domain, turns in B_SESSIONS:
        assert len(turns) == 5
        corpus.append({
            "request_id": rid,
            "part": "B",
            "domain": domain,
            "turns": turns,
            "max_new_tokens": 200,
        })
        rid += 1
    return corpus


if __name__ == "__main__":
    corpus = build()
    out = Path(__file__).with_name("corpus.json")
    blob = json.dumps(corpus, ensure_ascii=False, indent=1)
    out.write_text(blob, encoding="utf-8")
    n_a = sum(1 for c in corpus if c["part"] == "A")
    n_b = sum(1 for c in corpus if c["part"] == "B")
    est = n_a * 80 + n_b * 5 * 200
    digest = hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]
    print(f"part A requests : {n_a}  ({len(A_DOMAINS)} domains x 30)")
    print(f"part B sessions : {n_b}  (5 turns each)")
    print(f"generated tokens (target) : ~{est}")
    print(f"corpus sha256[:16] : {digest}")
    print(f"written : {out}")
